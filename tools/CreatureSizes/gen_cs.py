"""Step 3 of the creature size table (see README.md): writes CreatureSizes.g.cs.

usage: python gen_cs.py <creatures.json> <setups_dims.json> <out .cs>

A creature's top is max(model height, selection sphere top) x its default scale, in centimetres.
Entries with no usable height (under 20 cm) are left out, so the HUD falls back to its estimate.
A few creatures are scaled absurdly (a 400x "colossal" that is a trick, not a monster); tops
over 120 m are capped.
"""
import json
import sys

creatures = json.load(open(sys.argv[1]))
dims = json.load(open(sys.argv[2]))

rows = []
for wcid, c in creatures.items():
    d = dims.get(str(c["setup"]))
    if not d:
        continue
    height, radius, sel_z, sel_r, sort_z, sort_r = d
    top = max(height, sel_z + sel_r) * c["scale"]
    if top < 0.2:
        continue
    rows.append((int(wcid), min(int(round(top * 100)), 12000)))
rows.sort()

lines = [
    "// <auto-generated> by tools/CreatureSizes (gen_cs.py); do not edit. </auto-generated>",
    "// Weenie class id -> the creature's top in centimetres (model height x default scale).",
    "namespace RynthCore.Engine.ImGuiBackend.Hud;",
    "",
    "internal static partial class CreatureSizes",
    "{",
    "    private static readonly int[] Wcids =",
    "    {",
]


def chunk(values, per=12):
    for i in range(0, len(values), per):
        yield ", ".join(str(v) for v in values[i:i + per]) + ","


lines += ["        " + l for l in chunk([r[0] for r in rows])]
lines += ["    };", "", "    private static readonly ushort[] TopCm =", "    {"]
lines += ["        " + l for l in chunk([r[1] for r in rows], 16)]
lines += ["    };", "}", ""]
open(sys.argv[3], "w", encoding="utf-8", newline="\n").write("\n".join(lines))
print(len(rows), "creatures written to", sys.argv[3])
